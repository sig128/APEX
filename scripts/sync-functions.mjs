// Copy the API from backend/ into functions/apex/ so Cloud Functions runs exactly the code the
// local server runs (and the tests cover). Runs before every deploy (firebase.json predeploy);
// run it by hand before `firebase emulators:start`. functions/apex/ is generated: don't edit it.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const from = path.join(root, 'backend')
const to = path.join(root, 'functions', 'apex')

const FILES = ['app.js', 'streamChat.js', 'anthropicWebTools.js', 'oddsEvents.js', 'sportsConfig.js', 'adminSportsRoutes.js']
const DIRS = ['src', 'prompts']

fs.rmSync(to, { recursive: true, force: true })
fs.mkdirSync(to, { recursive: true })
let n = 0
for (const f of FILES) {
  fs.copyFileSync(path.join(from, f), path.join(to, f))
  n++
}
function copyDir(src, dst) {
  fs.mkdirSync(dst, { recursive: true })
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    if (e.name.startsWith('.')) continue
    const s = path.join(src, e.name)
    const d = path.join(dst, e.name)
    if (e.isDirectory()) copyDir(s, d)
    else if (/\.(js|mjs|json)$/.test(e.name)) {
      fs.copyFileSync(s, d)
      n++
    }
  }
}
for (const d of DIRS) copyDir(path.join(from, d), path.join(to, d))
fs.writeFileSync(path.join(to, 'package.json'), `${JSON.stringify({ type: 'module', private: true, description: 'Generated by scripts/sync-functions.mjs from backend/. Do not edit.' }, null, 2)}\n`)
fs.writeFileSync(path.join(to, 'README.txt'), 'Generated from backend/ by scripts/sync-functions.mjs before each deploy. Edit backend/, not this folder.\n')
console.log(`synced ${n} files from backend/ to functions/apex/`)
