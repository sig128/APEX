export const isAdvanced = (x) => x.level === 'advanced'

/** What each viewer gets: everything for members, and for everyone else the advanced entries' name and definition only. */
export function legendFor(member) {
  return {
    categories: CATEGORIES,
    entries: ENTRIES.map((x) => (member || !isAdvanced(x) ? { ...x, locked: false } : { id: x.id, term: x.term, cat: x.cat, level: x.level, def: x.def, see: x.see, locked: true })),
    member,
  }
}
